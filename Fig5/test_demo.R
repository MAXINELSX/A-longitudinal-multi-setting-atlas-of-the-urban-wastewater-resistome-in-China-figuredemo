args<-commandArgs(trailingOnly=TRUE)
flag<-grep('^--file=',commandArgs(FALSE),value=TRUE)
root<-dirname(normalizePath(sub('^--file=','',flag[1]),winslash='/'))
out<-if(length(args))args[1] else file.path(root,'demo_output')
stopifnot(file.exists(file.path(out,'panel_status.csv')))
status<-read.csv(file.path(out,'panel_status.csv'))
stopifnot(nrow(status)==6L,all(grepl('^PASS',status$Status)))
stopifnot(!file.exists(file.path(out,'DEMO_SCOPE.txt')))
s<-read.csv(file.path(out,'sample_summaries.csv'))
x<-read.csv(file.path(root,'input/abundance.csv'))
stopifnot(nrow(s)==72L,nrow(x)==7344L,!anyDuplicated(s$Sample))
totals<-aggregate(Abundance~Sample,x,sum)
stopifnot(isTRUE(all.equal(s$Total_abundance,totals$Abundance[match(s$Sample,totals$Sample)],tolerance=1e-12)))
c<-read.csv(file.path(out,'e/six_setting_contrasts_BH.csv'))
stopifnot(nrow(c)==6L,all(is.finite(c$P)),all(c$P>=0 & c$P<=1),all(c$q_BH>=0 & c$q_BH<=1))
d<-read.csv(file.path(out,'d/Fig5d_PCoA_stats.csv'))
stopifnot(nrow(d)==2L,all(d$PermutationsRequested==99L),all(is.finite(d$P)))
plots<-c('bc/Fig5b_alluvial.pdf','bc/Fig5c_Venn_and_type_donuts.pdf','d/Fig5d_PCoA.pdf',
         'e/Fig5e.pdf','fg/Fig5f_TierI_city_composition.pdf','fg/Fig5g_TierI_monthly_bubble.pdf')
stopifnot(all(file.exists(file.path(out,plots))),all(file.info(file.path(out,plots))$size>1000))
