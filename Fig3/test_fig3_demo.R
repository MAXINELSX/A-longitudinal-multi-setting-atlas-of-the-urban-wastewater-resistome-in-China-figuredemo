args <- commandArgs(trailingOnly = TRUE)
script <- sub("^--file=", "", grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)[1])
root <- normalizePath(if (length(args)) args[[1]] else dirname(normalizePath(script, mustWork = TRUE)), mustWork = TRUE)
stopifnot("Demo implementation is missing" = file.exists(file.path(root, "run_demo.R")))
source(file.path(root, "run_demo.R"))
source(file.path(root, "audit_fig3_inputs.R"))
raw <- read_nonempty_tsv(file.path(root, "input", "mag_burden.tsv"))
adapted <- prepare_fig3d_demo(raw)
stopifnot(nrow(adapted$id_map) == nrow(raw))
stopifnot(!anyDuplicated(adapted$id_map$demo_mag_uid))
stopifnot(identical(adapted$id_map$original_bin_id, raw$bin_id))
stopifnot(sum(adapted$id_map$included_in_species_analysis) == 171L)
stopifnot(nrow(adapted$excluded) == 45L)
stopifnot(nrow(adapted$metadata) == 18L)
stopifnot(all(adapted$metadata$synthetic_metadata), !"metadata_provenance" %in% names(adapted$metadata))
stopifnot(all(adapted$mags$total_burden == raw$arg_burden[adapted$mags$source_row]))
stopifnot(all(is.na(adapted$summary$prop_pathogen_mags)))
stopifnot(all(adapted$metadata$City == raw$City[match(adapted$metadata$original_sample, raw$Sample)]))
stopifnot(all(adapted$metadata$Setting == normalize_demo_setting(raw$Sample_Type[match(adapted$metadata$original_sample, raw$Sample)])))
cat("PASS_FIG3D_ADAPTER\n")
