script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
root <- if (exists("panel_demo_root", inherits = FALSE)) panel_demo_root else dirname(dirname(normalizePath(script, winslash = "/", mustWork = TRUE)))
args <- commandArgs(TRUE)
if (length(args) != 2L || args[1] != "--output") stop("Usage: Rscript tests/test_outputs.R --output DIR")
out <- args[2]
raw <- read.delim(file.path(root, "input", "processed_fractions.tsv"), check.names = FALSE)
actual <- read.delim(file.path(out, "fraction_plot_input.tsv"), check.names = FALSE)
stopifnot(nrow(actual) == 41L, isTRUE(all.equal(actual, raw, check.attributes = FALSE)))
totals <- read.delim(file.path(out, "fraction_totals.tsv"))
stopifnot(abs(totals$selected_fraction_of_all_classified_ORFs - sum(raw$Fraction_of_all_classified_ORFs)) < 1e-12)
stopifnot(abs(totals$selected_fraction_of_all_classified_ORFs - 0.273137) < 1e-12)
status <- read.csv(file.path(out, "run_status.csv"))
stopifnot(identical(status$status, c("PASS_PROCESSED_FRACTION_DEMO", "NOT_RUN_COUNT_INPUT_UNAVAILABLE")))
files <- file.path(out, c("fraction_flow.png", "fraction_flow.pdf"))
stopifnot(all(file.exists(files)), all(file.info(files)$size > 1000L))
stopifnot(!any(file.exists(file.path(out, c("SCOPE.txt", "DEMO_SCOPE.txt", "warnings.txt")))))
cat("PASS_FIG3B_OUTPUTS\n")
