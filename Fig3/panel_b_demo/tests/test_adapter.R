script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
root <- dirname(dirname(normalizePath(script, winslash = "/", mustWork = TRUE)))
adapter <- file.path(root, "run_demo.R")
if (!file.exists(adapter)) stop("FAIL: processed-fraction adapter is not implemented.")
source(adapter)
raw <- read.delim(file.path(root, "input", "processed_fractions.tsv"), check.names = FALSE)
d <- prepare_fraction_paths(raw)
stopifnot(nrow(d) == 41L, ncol(d) == ncol(raw), identical(d, raw))
stopifnot(identical(unique(d$ARG_type), c("aminoglycoside", "antibacterial_fatty_acid", "bacitracin", "beta_lactam")))
stopifnot(abs(sum(d$Fraction_of_all_classified_ORFs) - 0.273137) < 1e-12)
stopifnot(!any(grepl("count|n_ARG|denominator", names(d), ignore.case = TRUE)))
must_fail <- function(expr) stopifnot(inherits(tryCatch(force(expr), error = identity), "error"))
bad <- raw; bad$Fraction_of_all_classified_ORFs[1] <- -0.1
must_fail(prepare_fraction_paths(bad))
bad <- raw; bad$Fraction_of_all_classified_ORFs[1] <- 2
must_fail(prepare_fraction_paths(bad))
must_fail(prepare_fraction_paths(rbind(raw, raw[1, ])))
bad <- raw; bad$Setting[1] <- "Unknown"
must_fail(prepare_fraction_paths(bad))
p <- plot_fraction_paths(d)
built <- ggplot2::ggplot_build(p)
stopifnot(abs(sum(built$data[[1]]$ymax[built$data[[1]]$x == 1] - built$data[[1]]$ymin[built$data[[1]]$x == 1]) - sum(raw$Fraction_of_all_classified_ORFs)) < 1e-12)
stopifnot(grepl("Reported fraction", p$labels$y, fixed = TRUE))
out <- tempfile("fraction_demo_test_")
result <- run_panel_b_demo(root, output_dir = out)
expected <- c("fraction_flow.png", "fraction_flow.pdf", "fraction_plot_input.tsv", "fraction_totals.tsv", "run_status.csv", "package_versions.csv")
stopifnot(all(file.exists(file.path(out, expected))))
stopifnot(!any(file.exists(file.path(out, c("SCOPE.txt", "DEMO_SCOPE.txt", "warnings.txt")))))
written <- read.delim(file.path(out, "fraction_plot_input.tsv"), check.names = FALSE)
stopifnot(isTRUE(all.equal(written, raw, check.attributes = FALSE)))
stopifnot(identical(result$status$status, c("PASS_PROCESSED_FRACTION_DEMO", "NOT_RUN_COUNT_INPUT_UNAVAILABLE")))
cat("PASS_FIG3B_ADAPTER\n")
