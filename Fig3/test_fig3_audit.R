args <- commandArgs(trailingOnly = TRUE)
script <- sub("^--file=", "", grep("^--file=", commandArgs(trailingOnly = FALSE), value = TRUE)[1])
root <- if (length(args)) args[[1]] else dirname(normalizePath(script, mustWork = TRUE))
root <- normalizePath(root, mustWork = TRUE)
stopifnot("Fig3 audit implementation is missing" = file.exists(file.path(root, "audit_fig3_inputs.R")))
source(file.path(root, "audit_fig3_inputs.R"))
inputs <- file.path(root, "input")
result <- audit_fig3_inputs(inputs)
stopifnot(result$inventory$nonempty_rows[result$inventory$file == "sample_metadata.tsv"] == 18L)
stopifnot(result$inventory$empty_rows_removed[result$inventory$file == "sample_metadata.tsv"] == 2589L)
stopifnot(nrow(result$duplicate_mag_records) == 6L)
stopifnot(length(unique(result$duplicate_mag_records$mag_uid)) == 3L)
stopifnot(nrow(result$metadata_comparison) == 18L)
stopifnot(any(!result$metadata_comparison$city_equal), any(!result$metadata_comparison$setting_equal))
stopifnot(all(result$panel_readiness$status == "BLOCKED"))
stopifnot(identical(result$input_hashes$md5, unname(tools::md5sum(file.path(inputs, result$input_hashes$file)))))
cat("PASS_FIG3_AUDIT duplicate_ids=3\n")
