cmd <- commandArgs(trailingOnly = FALSE)
root <- dirname(normalizePath(sub('^--file=', '', cmd[grepl('^--file=', cmd)][1]), winslash = '/', mustWork = TRUE))
args <- commandArgs(trailingOnly = TRUE)
if (length(args) && (length(args) != 2L || args[1] != '--output')) stop('Usage: Rscript test_outputs.R [--output DIR]')
out <- if (length(args)) args[2] else file.path(root, 'reference_output')
files <- file.path(out, c('displayed_cells.tsv', 'panel_e_demo.pdf', 'panel_e_demo.png', 'diagnostics.tsv', 'versions.tsv', 'run_summary.txt'))
stopifnot(all(file.exists(files)), all(file.info(files)$size > 0))
d <- read.delim(files[1], check.names = FALSE)
x <- read.delim(file.path(root, 'input', 'precomputed_cells.tsv'), check.names = FALSE)
stopifnot(nrow(d) == 150L, length(unique(d$species)) == 6L, length(unique(d$arg_type)) == 5L, length(unique(d$scope)) == 5L)
stopifnot(identical(d[, c('scope', 'species', 'arg_type')], x[, c('scope', 'species', 'arg_type')]))
for (field in c('n_mag', 'n_arg_carrying_mags', 'pct_mags')) stopifnot(all(abs(d[[field]] - x[[field]]) < 1e-10))
stopifnot(all(abs(d$pct_mags - 100 * d$n_arg_carrying_mags / d$n_mag) < 1e-10))
stopifnot(!any(c('measurement', 'p', 'p_value', 'adjusted_p') %in% names(d)))
stopifnot(rawToChar(readBin(files[2], 'raw', n = 4)) == '%PDF')
png <- readBin(files[3], 'raw', n = 24)
stopifnot(identical(as.integer(png[1:8]), c(137L, 80L, 78L, 71L, 13L, 10L, 26L, 10L)))
stopifnot(sum(as.integer(png[17:20]) * 256^(3:0)) == 2160, sum(as.integer(png[21:24]) * 256^(3:0)) == 1224)
stopifnot(sum(read.delim(files[4])$count) == 0L)
stopifnot(identical(read.delim(files[5])$component, c('R', 'ggplot2', 'scales')))
stopifnot(!any(file.exists(file.path(out, c('SCOPE.txt', 'DEMO_SCOPE.txt', 'warnings.txt')))))
cat('PASS_FIG3E_OUTPUTS\n')
