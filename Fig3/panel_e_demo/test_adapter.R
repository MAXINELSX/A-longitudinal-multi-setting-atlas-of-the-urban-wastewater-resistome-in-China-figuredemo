args <- commandArgs(trailingOnly = FALSE)
script <- sub('^--file=', '', args[grepl('^--file=', args)][1])
root <- dirname(normalizePath(script, winslash = '/', mustWork = TRUE))
adapter <- file.path(root, 'adapter.R')
if (!file.exists(adapter)) stop('FAIL: the precomputed-cell adapter is not implemented.')
source(adapter)
x <- read.delim(file.path(root, 'input', 'precomputed_cells.tsv'), check.names = FALSE)
d <- prepare_panel_e(x)
stopifnot(nrow(d) == 150L, length(unique(d$species)) == 6L, length(unique(d$arg_type)) == 5L)
stopifnot(identical(d$pct_mags, x$pct_mags), identical(d$n_mag, x$n_mag), identical(d$n_arg_carrying_mags, x$n_arg_carrying_mags))
stopifnot(all(abs(d$pct_mags - 100 * d$n_arg_carrying_mags / d$n_mag) < 1e-10))
stopifnot(!any(c('measurement', 'p', 'p_value', 'adjusted_p') %in% names(d)))
expect_error <- function(expr) stopifnot(inherits(tryCatch({force(expr); NULL}, error = identity), 'error'))
expect_error(prepare_panel_e(rbind(x, x[1, ])))
bad <- x; bad$pct_mags[1] <- 101
expect_error(prepare_panel_e(bad))
bad <- x; bad$n_mag[1] <- 0
expect_error(prepare_panel_e(bad))
cat('PASS_FIG3E_ADAPTER\n')
