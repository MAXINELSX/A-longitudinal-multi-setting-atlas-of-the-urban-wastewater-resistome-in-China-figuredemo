args <- commandArgs(trailingOnly = TRUE)
script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
root <- if (length(args)) args[[1]] else dirname(normalizePath(script, mustWork = TRUE))
if (nzchar(Sys.getenv("DEMO_R_LIB"))) .libPaths(c(Sys.getenv("DEMO_R_LIB"), .libPaths()))
source(file.path(root, "panel_a_demo", "adapter.R"))
source(file.path(root, "panel_b_demo", "run_demo.R"))
source(file.path(root, "panel_c_demo", "run_demo.R"))
source(file.path(root, "panel_e_demo", "adapter.R"))
source(file.path(root, "run_demo.R"))
source(file.path(root, "audit_fig3_inputs.R"))
read_input <- function(panel, name) read.delim(file.path(root, paste0("panel_", panel, "_demo"), "input", name), check.names = FALSE)
a <- prepare_panel_a(read_input("a", "relative_abundance.tsv"), read_input("a", "metadata.tsv"))
b <- prepare_fraction_paths(read_input("b", "processed_fractions.tsv"))
c <- prepare_contigs(read_input("c", "contig_observations.tsv"))
s <- prepare_summary(read_input("c", "setting_summary.tsv"))
e <- prepare_panel_e(read_input("e", "precomputed_cells.tsv"))
plots <- list(plot_panel_a(a), plot_fraction_paths(b), plot_setting_summary(s), plot_contig_observations(c), plot_panel_e(e))
titles <- c("Figure 3a", "Figure 3b", "Figure 3c", "Figure 3c", "Figure 3e")
for (i in seq_along(plots)) {
  stopifnot(identical(plots[[i]]$labels$title, titles[i]))
  stopifnot(is.null(plots[[i]]$labels$subtitle), is.null(plots[[i]]$labels$caption))
}
stopifnot(!"measurement" %in% names(a), !"measurement" %in% names(e))
stopifnot(!any(vapply(plots[[3]]$layers, function(x) inherits(x$geom, "GeomText"), logical(1))))
d <- prepare_fig3d_demo(read_nonempty_tsv(file.path(root, "input", "mag_burden.tsv")))
stopifnot(!"metadata_provenance" %in% names(d$metadata), all(d$metadata$synthetic_metadata))
stopifnot(all(d$id_map$handling %in% c("INCLUDED", "NO_SPECIES")))
audit <- audit_fig3_inputs(file.path(root, "input"))
stopifnot("reason_code" %in% names(audit$panel_readiness), !"reason" %in% names(audit$panel_readiness))
cat("PASS_FIG3_CLEAN\n")
