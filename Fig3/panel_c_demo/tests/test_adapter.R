script <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
root <- dirname(dirname(normalizePath(script, winslash = "/", mustWork = TRUE)))
adapter <- file.path(root, "run_demo.R")
if (!file.exists(adapter)) stop("FAIL: summary and contig adapters are not implemented.")
source(adapter)
s <- read.delim(file.path(root, "input", "setting_summary.tsv"), check.names = FALSE)
c <- read.delim(file.path(root, "input", "contig_observations.tsv"), check.names = FALSE)
stopifnot(identical(prepare_summary(s), s), nrow(s) == 4L, sum(s$N_samples) == 12L)
stopifnot(identical(prepare_contigs(c), c), nrow(c) == 12L, all(table(c$Setting) == 3L))
stopifnot(all(c$total_arg_contigs >= 40L & c$total_arg_contigs <= 100L))
for (i in seq_len(nrow(s))) {
  z <- c$mobile_fraction[c$Setting == s$Setting[i]]
  expected <- c(length(z), mean(z), median(z), quantile(z, .25), quantile(z, .75), min(z), max(z), sd(z))
  stopifnot(max(abs(as.numeric(s[i, -1]) - expected)) < 1e-12)
}
stopifnot(all(grepl("^Sample[0-9]+$", c$Sample)), !any(c("City", "PhysicalSite", "Sample_Date") %in% names(c)))
stopifnot(max(abs(c$mobile_fraction - c$mobile_arg_contigs / c$total_arg_contigs)) < 1e-8)
must_fail <- function(expr) stopifnot(inherits(tryCatch(force(expr), error = identity), "error"))
bad <- s; bad$Q1[1] <- bad$Q3[1] + .1
must_fail(prepare_summary(bad))
must_fail(prepare_summary(rbind(s, s[1, ])))
bad <- c; bad$total_arg_contigs[1] <- 0
must_fail(prepare_contigs(bad))
bad <- c; bad$mobile_fraction[1] <- .99
must_fail(prepare_contigs(bad))
bad <- c; bad$mobile_arg_contigs[1] <- bad$mobile_arg_contigs[1] + .5
must_fail(prepare_contigs(bad))
ps <- plot_setting_summary(s)
pc <- plot_contig_observations(c)
stopifnot(nrow(ps$data) == 4L, nrow(pc$data) == 12L)
stopifnot(grepl("contig", ps$labels$y, fixed = TRUE))
stopifnot(grepl("contig", pc$labels$y, fixed = TRUE))
stopifnot(!any(vapply(pc$layers, function(x) inherits(x$stat, "StatSignif"), logical(1))))
out <- tempfile("summary_contig_test_")
result <- run_panel_c_demo(root, output_dir = out)
expected <- c("setting_summary.png", "setting_summary.pdf", "contig_violin.png", "contig_violin.pdf", "setting_summary_plot_input.tsv", "contig_plot_input.tsv", "contig_descriptive_statistics.tsv", "run_status.csv", "package_versions.csv")
stopifnot(all(file.exists(file.path(out, expected))))
stopifnot(!any(file.exists(file.path(out, c("SCOPE.txt", "DEMO_SCOPE.txt", "warnings.txt")))))
stopifnot(isTRUE(all.equal(read.delim(file.path(out, "setting_summary_plot_input.tsv")), s, check.attributes = FALSE)))
stopifnot(isTRUE(all.equal(read.delim(file.path(out, "contig_plot_input.tsv")), c, check.attributes = FALSE)))
stopifnot(identical(result$status$status, c("PASS_SUMMARY_DISPLAY_ONLY", "PASS_CONTIG_PLOT_ONLY", "NOT_RUN_ANNOTATION_INPUT_UNAVAILABLE")))
cat("PASS_FIG3C_ADAPTER\n")
